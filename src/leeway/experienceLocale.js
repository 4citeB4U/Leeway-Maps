let selected;
try {
  selected = localStorage.getItem('leeway.maps.language');
} catch {}
let current = LANGUAGES.some((l) => l.code === selected) ? selected : 'en';
export function getLanguage() {
  return LANGUAGES.find((l) => l.code === current);
}
export function translate(text, code = current) {
  const index = LANGUAGES.findIndex((l) => l.code === code) - 1;
  return index >= 0 ? rows[text]?.[index] || text : text;
}
export function canonicalMapCommand(text) {
  const value = String(text || '')
    .normalize('NFC')
    .trim()
    .toLocaleLowerCase();
  for (const key of [
    'Directions',
    'Weather',
    'Use my location',
    'Optimize stops',
    'Review route',
  ]) {
    if (
      [key, ...rows[key]].some((label) => label.toLocaleLowerCase() === value)
    ) {
      return {
        Directions: 'Open directions',
        Weather: 'Show weather radar',
        'Use my location': 'Use my location',
        'Optimize stops': 'Optimize stops',
        'Review route': 'Review route',
      }[key];
    }
  }
  return text;
}
export function setLanguage(code) {
  if (!LANGUAGES.some((l) => l.code === code))
    throw new Error('Unsupported interface language.');
  current = code;
  try {
    localStorage.setItem('leeway.maps.language', code);
  } catch {}
  globalThis.document?.documentElement.setAttribute('lang', code);
  globalThis.dispatchEvent?.(new Event('leeway:language'));
}
export function languageOptions(code = current) {
  return LANGUAGES.map(
    (l) =>
      `<option value="${l.code}" ${l.code === code ? 'selected' : ''}>${l.name}</option>`,
  ).join('');
}

/** Translate only authored exact UI labels; never reinterpret user data or map/provider records. */
export function mountLocaleLabels(documentRef = document) {
  const originals = new WeakMap(),
    attributeOriginals = new WeakMap();
  function visit(node) {
    if (node.nodeType === 3) {
      if (
        node.parentElement?.closest(
          'script,style,textarea,option,.lal-log,[translate="no"]',
        )
      )
        return;
      const prior = originals.get(node);
      const source =
        prior && node.nodeValue === prior.rendered
          ? prior.source
          : node.nodeValue;
      const key = source.trim();
      if (!rows[key]) return;
      const rendered = source.replace(key, translate(key));
      originals.set(node, { source, rendered });
      if (node.nodeValue !== rendered) node.nodeValue = rendered;
    } else {
      if (node.nodeType === 1 && !node.closest('[translate="no"]')) {
        let saved = attributeOriginals.get(node);
        if (!saved) {
          saved = {};
          attributeOriginals.set(node, saved);
        }
        for (const attr of ['aria-label', 'placeholder', 'title']) {
          const value = node.getAttribute(attr);
          if (value === null) continue;
          const prior = saved[attr];
          const source =
            prior && prior.rendered === value ? prior.source : value;
          if (!rows[source]) continue;
          const rendered = translate(source);
          saved[attr] = { source, rendered };
          if (value !== rendered) node.setAttribute(attr, rendered);
        }
      }
      for (const child of node.childNodes || []) visit(child);
    }
  }
  const refresh = () => {
    documentRef.documentElement.lang = current;
    visit(documentRef.body);
  };
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'characterData') visit(record.target);
      else record.addedNodes.forEach(visit);
    }
  });
  refresh();
  observer.observe(documentRef.body, {
    subtree: true,
    childList: true,
    characterData: true,
  });
  globalThis.addEventListener('leeway:language', refresh);
  return () => {
    observer.disconnect();
    globalThis.removeEventListener('leeway:language', refresh);
  };
}
